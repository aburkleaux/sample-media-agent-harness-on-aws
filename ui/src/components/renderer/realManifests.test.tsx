/**
 * @vitest-environment jsdom
 */
import { describe, it, expect } from 'vitest';
import { render } from '@testing-library/react';
import { theme } from '../../styles/tokens';
import { resolveTemplate } from './templates/ManifestRouter';
import shots from './__fixtures__/shot-segmentation.manifest.json';
import diarization from './__fixtures__/speech-diarization.manifest.json';
import faces from './__fixtures__/face-recognition.manifest.json';
import stems from './__fixtures__/audio-stems.manifest.json';
import images from './__fixtures__/generated-images.manifest.json';

/**
 * End-to-end contract across the language boundary.
 *
 * These fixtures are REAL Render Agent output, generated by
 * agent/scripts/emit_render_fixtures.py from the sidecar shapes of completed jobs and
 * restricted to the artifacts that survive the job registry's renderable filter. A
 * Python test fails if they drift from current agent behaviour.
 *
 * Every other test in this area checks one side only: the agent suite asserts what
 * the manifest contains, the template suite asserts what a template consumes. Both
 * passed while the router handed direct-prop templates nothing and they rendered
 * blank. This file resolves the template the same way the app does and renders the
 * actual manifest, so that gap cannot reopen.
 */

// Mirrors ManifestRouter's data shape.
const routerData = (m: Record<string, unknown>) => ({ ...m, manifest: m });

function renderManifest(m: Record<string, unknown>) {
  const Template = resolveTemplate(m.template);
  return render(<Template data={routerData(m) as never} title="Result" theme={theme} />);
}

describe('real agent manifests render', () => {
  it('shot segmentation shows every shot with its type', () => {
    // Current agent output: shots render in the ONE timeline container. (Stored manifests that
    // still say `video-markers` resolve here too via the registry alias — covered in
    // templateFold.test.tsx, together with the src-only shape that template used to emit.)
    expect(shots.template).toBe('nle-timeline');
    const { container } = renderManifest(shots as never);
    // the video is playable
    expect(container.querySelector('video')?.getAttribute('src')).toContain('segment_0000.mp4');
    // one row per detected shot — the reported bug was a single segment
    expect(shots.markers.length).toBeGreaterThan(1);
    // Every shot is still reachable AND still carries its type. The old marker-strip template
    // printed the category as a text row; the timeline puts each shot on the shared gutter as a
    // click-to-seek tick whose tooltip names the type. Asserting the tooltip (not textContent)
    // is what proves the fold moved the information rather than dropping it.
    const markerTitles = Array.from(container.querySelectorAll('button[title]'))
      .map((b) => b.getAttribute('title') ?? '');
    for (const mk of shots.markers) {
      expect(
        markerTitles.some((title) => title.includes(mk.category)),
        `no marker tooltip mentions shot type "${mk.category}"`,
      ).toBe(true);
    }
    // The shots lane exists and is labelled with the count.
    expect(container.textContent).toContain(`Shots · ${shots.markers.length}`);
    // real duration, not the 600s fallback
    expect(shots.duration).toBe(30.03);
  });

  it('diarization shows a lane per speaker', () => {
    expect(diarization.template).toBe('composite-timeline');
    const { container, getAllByText } = renderManifest(diarization as never);
    const speakers = Array.from(new Set(diarization.segments.map((s) => s.group)));
    expect(speakers.length).toBe(2);
    // each speaker appears in the lane strip AND the timecode table below
    for (const s of speakers) expect(getAllByText(String(s)).length).toBeGreaterThan(0);
    // lanes are drawn, not just a flat list
    expect(container.querySelectorAll('button').length).toBeGreaterThanOrEqual(diarization.segments.length);
  });

  it('faces shows who was found, with names and a timeline', () => {
    expect(faces.template).toBe('image-annotated');
    const { container, getAllByText } = renderManifest(faces as never);
    // a real thumbnail is displayed
    expect(container.querySelector('img')?.getAttribute('src')).toContain('person_0000.jpg');
    // the identified person is named
    // named in the gallery selector and in the people table
    expect(getAllByText('Kawhi Leonard').length).toBeGreaterThan(0);
    // and the appearance lanes exist against the full media duration
    expect(faces.duration).toBe(300.1);
    expect(faces.segments.length).toBeGreaterThan(0);
  });

  it('every fixture resolves to a real template, not the fallback', () => {
    for (const m of [shots, diarization, faces]) {
      const T = resolveTemplate(m.template);
      const fallback = resolveTemplate('definitely-not-registered');
      expect(T).not.toBe(fallback);
    }
  });

  it('no fixture is an error manifest', () => {
    for (const m of [shots, diarization, faces]) {
      expect((m as { errors?: unknown[] }).errors ?? []).toEqual([]);
    }
  });
});

/**
 * Invariants across EVERY fixture.
 *
 * Two render regressions shipped in one day that these would have caught at
 * `npx vitest run` speed:
 *
 *   1. A suppression gate treated `tracks: []` as "nothing to draw" and discarded
 *      manifests. generic-preview carries its content in artifacts/sources, so
 *      image rendering broke completely -- correct manifests were written and never
 *      became tabs. No image fixture existed, so nothing failed.
 *
 *   2. Analysis views referenced the M2C proxy via a PRESIGNED s3 url signed by a
 *      role that could not read that bucket: well-formed, unexpired, permanently
 *      403. The browser got XML and showed a black player stuck at 0:00.
 *
 * So: every fixture must put something on screen, and no fixture may point the
 * browser at a presigned s3 url.
 */
const ALL_FIXTURES: Array<[string, Record<string, unknown>]> = [
  ['shot-segmentation', shots as never],
  ['speech-diarization', diarization as never],
  ['face-recognition', faces as never],
  ['audio-stems', stems as never],
  ['generated-images', images as never],
];

describe('every real manifest puts something on screen', () => {
  it.each(ALL_FIXTURES)('%s renders visible content', (_name, manifest) => {
    const { container } = renderManifest(manifest);
    const shown = container.querySelectorAll(
      'video, audio, img, canvas, table, button, [role="img"]',
    );
    expect(shown.length).toBeGreaterThan(0);
  });

  it('generated images show one img per image, not a blank panel', () => {
    // The exact shape the suppression gate discarded: content in artifacts,
    // tracks empty.
    expect((images as { tracks: unknown[] }).tracks).toHaveLength(0);
    expect((images as { artifacts: unknown[] }).artifacts).toHaveLength(2);
    const { container } = renderManifest(images as never);
    expect(container.querySelectorAll('img').length).toBeGreaterThanOrEqual(2);
  });

  it('audio stems render playable audio, not a caption-only timeline', () => {
    const { container } = renderManifest(stems as never);
    expect(container.querySelectorAll('audio, video').length).toBeGreaterThan(0);
  });

  it('no fixture points the browser at a presigned s3 url', () => {
    for (const [name, manifest] of ALL_FIXTURES) {
      const blob = JSON.stringify(manifest);
      // SigV2 (AWSAccessKeyId+Signature) and SigV4 (X-Amz-Signature) both carry
      // only the SIGNER's authority, which is how a render became a permanent 403.
      expect(blob, `${name} embeds a presigned url`).not.toMatch(/AWSAccessKeyId=/);
      expect(blob, `${name} embeds a presigned url`).not.toMatch(/X-Amz-Signature=/);
    }
  });
});
