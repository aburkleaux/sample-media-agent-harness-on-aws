"""Keep the shared render fixtures honest.

The fixtures in ui/src/components/renderer/__fixtures__ are real Render Agent output
that the UI test suite renders. If agent behaviour changes without regenerating them,
the UI would keep asserting against a manifest the agent no longer produces — so the
cross-language check would silently stop meaning anything.
"""
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SCRIPT = ROOT / "scripts" / "emit_render_fixtures.py"
FIXTURES = ROOT.parent / "ui" / "src" / "components" / "renderer" / "__fixtures__"


def test_fixtures_match_current_agent_output():
    r = subprocess.run([sys.executable, str(SCRIPT), "--check"],
                       capture_output=True, text=True, cwd=str(ROOT))
    assert r.returncode == 0, (
        "render fixtures are stale — regenerate with "
        f"`python scripts/emit_render_fixtures.py`\n{r.stdout}\n{r.stderr}"
    )


# Generated by emit_render_fixtures.py from real sidecar shapes, and drift-checked.
GENERATED = {
    "shot-segmentation.manifest.json",
    "speech-diarization.manifest.json",
    "face-recognition.manifest.json",
    "audio-stems.manifest.json",
}

# CAPTURED from production, because _build_media_manifest is the deterministic media
# projection and returns no template for image-only input -- production images are
# rendered by the render-generic SKILL path, which the generator cannot reproduce.
# Not drift-checked, which is a real gap: if the image render path changes, this
# fixture goes stale silently. Recapture from a render manifest in S3.
CAPTURED = {"generated-images.manifest.json"}


def test_every_case_produced_a_fixture():
    names = {p.name for p in FIXTURES.glob("*.manifest.json")}
    assert names == GENERATED | CAPTURED, names


def test_audio_only_output_is_not_described_as_video():
    """The generator's probe stub used to claim every url was video/mp4.

    It was only ever correct because each case happened to be video-ish, and it made
    the diarization fixture -- whose media is a .wav -- report mimeType video/mp4.
    A fixture that misdescribes its own media cannot prove a template renders it.
    """
    import json
    m = json.loads((FIXTURES / "speech-diarization.manifest.json").read_text())
    assert m["mimeType"] == "audio/wav"
    stems = json.loads((FIXTURES / "audio-stems.manifest.json").read_text())
    assert stems["mimeType"].startswith("audio/")


def test_stated_duration_outranks_the_last_span():
    """A five-minute video whose faces appear at 63s must not be 65s long.

    The analysis-only manifest first derived duration from the projected spans, which
    put an appearance one minute in at the far right of the timeline.
    """
    import json
    m = json.loads((FIXTURES / "face-recognition.manifest.json").read_text())
    assert m["duration"] == 300.1
    first = min(s["start"] for s in m["segments"])
    assert first / m["duration"] < 0.3, "appearance placed too far along the timeline"


def test_speech_time_is_not_treated_as_media_duration():
    """60s of speech can be spread across a 5-minute recording.

    The measured audio track is the authority for the timeline; the speech content
    (sentence spans) must not compress it. v6 final_transcript reports no top-level
    total_speech_sec, so the summary carries sentence/speaker counts instead.
    """
    import json
    m = json.loads((FIXTURES / "speech-diarization.manifest.json").read_text())
    assert m["duration"] == 300.0, "duration must come from the audio track, not the speech spans"
    # the last sentence ends at 36.0s — far short of the 300s recording
    assert m["duration"] > 36.0
    assert m["metadata"]["num_global_speakers"] == 2
